async function seed() {
  console.log(`Starting to seed ${ALL_SYSTEM_MODULES.length} system modules into Supabase...`);

  // Fetch existing modules to preserve custom toggles if any
  const { data: existing } = await supabase.from("system_modules").select("key, is_enabled, status");
  const existingMap = new Map((existing || []).map((m) => [m.key, m]));

  const payload = ALL_SYSTEM_MODULES.map((mod) => {
    const prev = existingMap.get(mod.key);
    return {
      ...mod,
      is_enabled: prev !== undefined ? prev.is_enabled : mod.is_enabled,
      status: prev !== undefined ? prev.status : mod.status,
      updated_at: new Date().toISOString(),
    };
  });

  const { error } = await supabase.from("system_modules").upsert(payload, { onConflict: "key" });

  if (error) {
    console.error("Failed to seed system modules:", error);
    process.exit(1);
  }

  console.log(`Successfully seeded/updated ${payload.length} system modules in database!`);
}

seed();
