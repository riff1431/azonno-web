export type TranslationKey = keyof typeof enTranslations;

const translations = {
  en: enTranslations,
  bn: enTranslations,
} as const;

export type TranslationDict = typeof translations.en;

export function getTranslations(lang: AdminLang): TranslationDict {
  return translations[lang] as TranslationDict;
}

export function createTranslator(lang: AdminLang) {
  const dict = getTranslations(lang);
  return function t(key: TranslationKey, fallback?: string): string {
    return (dict[key] as string) ?? fallback ?? key;
  };
}

export { translations };
